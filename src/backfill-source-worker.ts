import { resolve, join } from "node:path";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import {
  createBackfillSnapshotReader,
  type BackfillSourceReader,
  type BackfillUnavailable,
  type SqliteBackfillSource,
} from "./backfill-source.js";
import { createBackfillSnapshots } from "./backfill-snapshot.js";
import {
  projectBackfillTranscript,
  BackfillProjectionError,
  type BackfillProjectionHost,
} from "./backfill-projection.js";
import type { PluginConfig } from "./types.js";

type ModuleLoader = (specifier: string) => Promise<unknown>;
type Config = Record<string, unknown>;
type Dependencies = {
  snapshots: Pick<ReturnType<typeof createBackfillSnapshots>, "get" | "close">;
  reader(root: string): BackfillSourceReader;
};
class BackfillHostError extends Error {}
function snapshotReaderFailure(
  stage: string,
  error: unknown,
): BackfillHostError {
  // Preserve only messages generated by our IPC/service boundary, never native host errors.
  const safePrefixes = [
    "Unsupported OpenClaw host:",
    "Selected OpenClaw config ",
    "Selected Hindsight plugin config ",
    "Invalid OpenClaw ",
    "Invalid backfill ",
    "Backfill source ",
    "Backfill snapshot ",
    "OpenClaw backfill source worker ",
    "Unable to run OpenClaw backfill ",
    "Unable to send OpenClaw backfill ",
    "Unable to read selected OpenClaw config",
  ];
  const detail =
    error instanceof Error &&
    safePrefixes.some((prefix) => error.message.startsWith(prefix))
      ? `: ${error.message}`
      : "";
  return new BackfillHostError(
    `OpenClaw snapshot reader ${stage} failed${detail}`,
  );
}
function object(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === "object" && !Array.isArray(value);
}
function identity(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0;
}
function projectionHost(
  module: Record<string, unknown>,
): module is Record<string, unknown> & BackfillProjectionHost {
  const manager = module.SessionManager;
  return (
    typeof manager === "function" &&
    "fromEntries" in manager &&
    typeof manager.fromEntries === "function" &&
    typeof module.buildSessionContext === "function"
  );
}
function sqliteSource(value: unknown, agentId: string): SqliteBackfillSource {
  if (
    !object(value) ||
    value.agentId !== agentId ||
    !identity(value.agentId) ||
    !identity(value.sessionId) ||
    !identity(value.storePath) ||
    (value.sessionKey !== undefined && !identity(value.sessionKey)) ||
    (value.artifactKind !== "active-session" &&
      value.artifactKind !== "retained-session")
  )
    throw new BackfillHostError("Invalid OpenClaw SQLite corpus identity");
  return {
    kind: "sqlite",
    agentId: value.agentId,
    sessionId: value.sessionId,
    storePath: value.storePath,
    artifactKind: value.artifactKind,
    ...(value.sessionKey !== undefined ? { sessionKey: value.sessionKey } : {}),
    ...(typeof value.updatedAtMs === "number" &&
    Number.isFinite(value.updatedAtMs)
      ? { updatedAtMs: value.updatedAtMs }
      : {}),
  };
}

/** The original-root process resolves paths and copies SQLite, never admits a source host reader. */
export function createBackfillWorkerService(
  loadModule: ModuleLoader,
  environment: NodeJS.ProcessEnv,
  injected?: Dependencies,
  snapshotMode = false,
): BackfillSourceReader {
  const env = { ...environment };
  let closed = false;
  let ownedScratch: string | undefined;
  let dependencies: Dependencies | undefined = injected;
  const readers = new Map<string, Promise<BackfillSourceReader>>();
  const activeReaders = new Set<BackfillSourceReader>();
  const selected = new Map<
    string,
    { logical: string; snapshotPath: string; reader: BackfillSourceReader }
  >();
  let prepared:
    | Promise<{
        config: Config;
        pluginConfig: PluginConfig;
        agentIds: string[];
      }>
    | undefined;
  async function publicModule(
    specifier: string,
  ): Promise<Record<string, unknown>> {
    try {
      const result = await loadModule(specifier);
      if (object(result)) return result;
    } catch {}
    throw new BackfillHostError(
      `Unsupported OpenClaw host: missing public module ${specifier}`,
    );
  }
  function prepare() {
    if (closed)
      return Promise.reject(
        new BackfillHostError("Backfill source reader is closed"),
      );
    prepared ??= (async () => {
      const health = await publicModule("openclaw/plugin-sdk/health");
      const scope = await publicModule(
        "openclaw/plugin-sdk/agent-scope-runtime",
      );
      if (
        typeof health.readConfigFileSnapshot !== "function" ||
        typeof scope.listAgentIds !== "function"
      )
        throw new BackfillHostError(
          "Unsupported OpenClaw host: missing public config or agent-scope helper",
        );
      let snapshot: unknown;
      try {
        snapshot = await health.readConfigFileSnapshot({
          observe: false,
          isolateEnv: true,
          pluginValidation: "core-only",
          recoverSuspicious: false,
        });
      } catch {
        throw new BackfillHostError("Unable to read selected OpenClaw config");
      }
      if (
        !object(snapshot) ||
        snapshot.exists !== true ||
        snapshot.valid !== true ||
        !object(snapshot.config)
      )
        throw new BackfillHostError(
          "Selected OpenClaw config is missing or invalid",
        );
      const config = snapshot.config;
      const agentIds: unknown = scope.listAgentIds(config);
      if (!Array.isArray(agentIds) || !agentIds.every(identity))
        throw new BackfillHostError("Invalid OpenClaw agent roster response");
      const plugins = object(config.plugins) ? config.plugins : {};
      const entries = object(plugins.entries) ? plugins.entries : {};
      const plugin = object(entries["hindsight-memory"])
        ? entries["hindsight-memory"]
        : {};
      if (plugin.config !== undefined && !object(plugin.config))
        throw new BackfillHostError(
          "Selected Hindsight plugin config is invalid",
        );
      return {
        config,
        pluginConfig: (plugin.config ?? {}) as PluginConfig,
        agentIds,
      };
    })();
    return prepared;
  }
  async function deps(): Promise<Dependencies> {
    if (!dependencies) {
      const scratch =
        env.HINDSIGHT_BACKFILL_SCRATCH_ROOT ??
        (ownedScratch = await mkdtemp(
          join(tmpdir(), "hindsight-backfill-worker-"),
        ));
      dependencies = {
        snapshots: createBackfillSnapshots(scratch),
        reader: createBackfillSnapshotReader,
      };
    }
    return dependencies;
  }
  async function validateAgentId(agentId: string): Promise<void> {
    const routing = await publicModule("openclaw/plugin-sdk/routing");
    if (typeof routing.normalizeAgentIdStrict !== "function")
      throw new BackfillHostError(
        "Unsupported OpenClaw host: missing public agent identity normalizer",
      );
    const normalized: unknown = routing.normalizeAgentIdStrict(agentId);
    if (
      !object(normalized) ||
      normalized.ok !== true ||
      normalized.value !== agentId
    )
      throw new BackfillHostError("Invalid backfill agent identity");
  }
  async function snapshotConfig(agentId: string): Promise<Config> {
    await validateAgentId(agentId);
    const prepared = await prepare();
    const agents = object(prepared.config.agents) ? prepared.config.agents : {};
    const entries = object(agents.entries) ? agents.entries : {};
    if (Object.hasOwn(entries, agentId)) return prepared.config;
    // A shared snapshot may encounter a retired filesystem agent after its first reader starts.
    // Extend only this scratch roster; public config validation remains the admission boundary.
    const config = {
      agents: { ownership: "explicit", entries: { ...entries, [agentId]: {} } },
      session: prepared.config.session,
    };
    if (!identity(env.OPENCLAW_CONFIG_PATH))
      throw new BackfillHostError(
        "Missing backfill snapshot configuration path",
      );
    await writeFile(env.OPENCLAW_CONFIG_PATH, JSON.stringify(config), {
      mode: 0o600,
    });
    const health = await publicModule("openclaw/plugin-sdk/health");
    if (typeof health.readConfigFileSnapshot !== "function")
      throw new BackfillHostError(
        "Unsupported OpenClaw host: missing public config reader",
      );
    const snapshot: unknown = await health.readConfigFileSnapshot({
      observe: false,
      isolateEnv: true,
      pluginValidation: "core-only",
      recoverSuspicious: false,
    });
    if (
      !object(snapshot) ||
      snapshot.exists !== true ||
      snapshot.valid !== true ||
      !object(snapshot.config)
    )
      throw new BackfillHostError("Backfill snapshot configuration is invalid");
    prepared.config = snapshot.config;
    return prepared.config;
  }
  async function select(agentId: string) {
    const cached = selected.get(agentId);
    if (cached) return cached;
    const { config, agentIds } = await prepare();
    await validateAgentId(agentId);
    const runtime = await publicModule(
      "openclaw/plugin-sdk/session-store-runtime",
    );
    if (
      typeof runtime.resolveStorePath !== "function" ||
      typeof runtime.resolveSessionStoreBackupPaths !== "function"
    )
      throw new BackfillHostError(
        "Unsupported OpenClaw host: missing public store path resolver",
      );
    const session = object(config.session) ? config.session : {};
    const logical: unknown = runtime.resolveStorePath(
      typeof session.store === "string" ? session.store : undefined,
      { agentId, env },
    );
    if (!identity(logical))
      throw new BackfillHostError("Invalid OpenClaw session store path");
    const family: unknown = runtime.resolveSessionStoreBackupPaths({
      agentId,
      storePath: logical,
    });
    if (!Array.isArray(family) || !family.every(identity))
      throw new BackfillHostError("Invalid OpenClaw store backup paths");
    // Identify SQLite's canonical base from the resolver's own sidecar family.
    const bases = family.filter(
      (path) =>
        family.includes(`${path}-wal`) && family.includes(`${path}-shm`),
    );
    if (bases.length !== 1)
      throw new BackfillHostError("Unable to resolve OpenClaw SQLite store");
    const dependencies = await deps();
    const snapshot = await dependencies.snapshots.get(bases[0]);
    if (snapshot.status !== "available") return snapshot;
    let pending = readers.get(snapshot.storePath);
    if (!pending) {
      pending = (async () => {
        const config = {
          agents: {
            ownership: "explicit",
            entries: Object.fromEntries(
              [...new Set([...agentIds, agentId])].map((id) => [id, {}]),
            ),
          },
          session: { store: snapshot.storePath },
        };
        await writeFile(
          join(snapshot.root, "openclaw.json"),
          JSON.stringify(config),
          { mode: 0o600 },
        );
        const reader = dependencies.reader(snapshot.root);
        activeReaders.add(reader);
        try {
          await reader.prepare();
        } catch (error) {
          throw snapshotReaderFailure("preparation", error);
        }
        return reader;
      })();
      readers.set(snapshot.storePath, pending);
    }
    const result = {
      logical,
      snapshotPath: snapshot.storePath,
      reader: await pending,
    };
    selected.set(agentId, result);
    return result;
  }
  async function snapshotDiscover(agentId: string, includeRetained: boolean) {
    const config = await snapshotConfig(agentId);
    const host = await publicModule(
      "openclaw/plugin-sdk/memory-core-host-engine-sessions",
    );
    if (typeof host.listSessionTranscriptCorpusEntriesForAgent !== "function")
      throw new BackfillHostError(
        "Unsupported OpenClaw host: missing released corpus reader",
      );
    let rows: unknown;
    try {
      rows = await host.listSessionTranscriptCorpusEntriesForAgent(agentId, {
        config,
        readOnly: true,
        includeRetainedSqlite: includeRetained,
        includeContentRevision: false,
      });
    } catch {
      return { status: "unavailable" as const, reason: "unavailable" };
    }
    if (!Array.isArray(rows))
      throw new BackfillHostError("Invalid OpenClaw corpus response");
    const sources: SqliteBackfillSource[] = [];
    for (const row of rows) {
      if (!object(row))
        throw new BackfillHostError("Invalid OpenClaw corpus row");
      if (
        row.artifactKind === "archive-artifact" ||
        row.transcriptSource !== "sqlite"
      )
        continue;
      const source = sqliteSource(row, agentId);
      if (includeRetained || source.artifactKind !== "retained-session")
        sources.push(source);
    }
    return { status: "available" as const, sources };
  }
  return {
    async prepare() {
      const { pluginConfig, agentIds } = await prepare();
      return { pluginConfig, agentIds };
    },
    async discover(agentId, includeRetained) {
      if (!identity(agentId))
        throw new BackfillHostError("Invalid backfill agent identity");
      if (snapshotMode) return snapshotDiscover(agentId, includeRetained);
      const target = await select(agentId);
      if ("status" in target) return target;
      let response: Awaited<ReturnType<BackfillSourceReader["discover"]>>;
      try {
        response = await target.reader.discover(agentId, includeRetained);
      } catch (error) {
        throw snapshotReaderFailure("discovery", error);
      }
      if (response.status !== "available") return response;
      return {
        status: "available",
        sources: response.sources.map((source) => ({
          ...sqliteSource(source, agentId),
          storePath: target.logical,
        })),
      };
    },
    async read(source) {
      sqliteSource(source, source.agentId);
      if (!snapshotMode) {
        const target = await select(source.agentId);
        if ("status" in target) return target;
        if (source.storePath !== target.logical)
          throw new BackfillHostError("Backfill source store identity changed");
        // The inner reader validates its explicit scratch path against its own config.
        try {
          return await target.reader.read({
            ...source,
            storePath: target.snapshotPath,
          });
        } catch (error) {
          throw snapshotReaderFailure("transcript read", error);
        }
      }
      const config = await snapshotConfig(source.agentId);
      const session = object(config.session) ? config.session : {};
      if (source.storePath !== session.store)
        throw new BackfillHostError("Backfill snapshot store identity changed");
      const runtime = await publicModule(
        "openclaw/plugin-sdk/session-store-runtime",
      );
      const projection = await publicModule(
        "openclaw/plugin-sdk/agent-sessions",
      );
      if (
        typeof runtime.loadTranscriptEvents !== "function" ||
        !projectionHost(projection)
      )
        throw new BackfillHostError(
          "Unsupported OpenClaw host: missing public transcript reader or projection",
        );
      try {
        const events: unknown = await runtime.loadTranscriptEvents({
          agentId: source.agentId,
          sessionId: source.sessionId,
          ...(source.sessionKey !== undefined
            ? { sessionKey: source.sessionKey }
            : {}),
          storePath: source.storePath,
          env,
        });
        if (!Array.isArray(events))
          return { status: "unavailable", reason: "unavailable" };
        return {
          status: "available",
          events: projectBackfillTranscript(
            events,
            source.sessionId,
            projection,
          ),
        };
      } catch (error) {
        return {
          status: "unavailable",
          reason:
            error instanceof BackfillProjectionError &&
            error.reason === "missing-transcript"
              ? "missing-transcript"
              : "unavailable",
        };
      }
    },
    async close() {
      closed = true;
      await Promise.allSettled(readers.values());
      for (const reader of activeReaders) await reader.close();
      await dependencies?.snapshots.close();
      if (ownedScratch)
        await rm(ownedScratch, { recursive: true, force: true });
    },
  };
}

function startWorker(): void {
  const service = createBackfillWorkerService(
    (specifier) => import(specifier),
    process.env,
    undefined,
    process.argv.includes("--snapshot-reader"),
  );
  let queue = Promise.resolve();
  process.on("disconnect", () => {
    void service.close().finally(() => process.exit(0));
  });
  process.on("message", (request: unknown) => {
    queue = queue.then(async () => {
      if (!object(request) || !Number.isSafeInteger(request.id)) return;
      const id = request.id;
      try {
        let value: unknown;
        switch (request.operation) {
          case "prepare":
            value = await service.prepare();
            break;
          case "discover":
            if (
              typeof request.agentId !== "string" ||
              typeof request.includeRetained !== "boolean"
            )
              throw new BackfillHostError("Invalid backfill discovery request");
            value = await service.discover(
              request.agentId,
              request.includeRetained,
            );
            break;
          case "read":
            value = await service.read(request.source as SqliteBackfillSource);
            break;
          case "close":
            await service.close();
            break;
          default:
            throw new BackfillHostError("Invalid backfill source operation");
        }
        if (request.operation === "close") {
          process.send?.({ id, ok: true, value }, () => process.exit(0));
        } else process.send?.({ id, ok: true, value });
      } catch (error) {
        process.send?.({
          id,
          ok: false,
          error:
            error instanceof BackfillHostError
              ? error.message
              : "OpenClaw backfill source worker failed",
        });
      }
    });
  });
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  startWorker();
}
